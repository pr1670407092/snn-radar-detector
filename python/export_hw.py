"""Export the integer SNN to .mem files consumed by the RTL / testbench."""
import argparse
import json
import os
import numpy as np
from convert_snn import load_model, build_snn, snn_forward

def pack_weight_file(Wq, path, lanes=32, w_bits=8):
    """Wq: (neurons, fanin) int.  RTL word = `lanes` signed lanes of `w_bits`."""
    n, f = Wq.shape
    assert f % lanes == 0, (n, f)
    mask = (1 << w_bits) - 1
    words = []
    for j in range(n):
        for c in range(f // lanes):
            word = 0
            for lane in range(lanes):
                word |= (int(Wq[j, c * lanes + lane]) & mask) << (w_bits * lane)
            words.append(word)
    with open(path, "w") as fh:
        for w in words:
            fh.write(f"{w:064x}\n")
    return len(words)


def pack_bias_file(bq, path):
    with open(path, "w") as fh:
        for v in bq:
            fh.write(f"{int(v) & 0xFFFFFF:06x}\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="models/ann_B.pt")
    ap.add_argument("--data", default="data/radar_merged.npz")
    ap.add_argument("--cal", type=int, default=2000)
    ap.add_argument("--pct", type=float, default=99.0)
    ap.add_argument("--T", type=int, default=16)
    ap.add_argument("--w-bits", type=int, default=8)
    ap.add_argument("--lanes", type=int, default=32)
    ap.add_argument("--scale", type=float, default=256.0/255.0)
    ap.add_argument("--cases", type=int, default=8)
    ap.add_argument("--outdir", default="weights")
    args = ap.parse_args()

    os.makedirs(args.outdir, exist_ok=True)
    os.makedirs("rtl", exist_ok=True)
    model, _ = load_model(args.model)
    d = np.load(args.data)
    cal_x = d["x_train"][:args.cal]
    x = d["x_test"]
    y = d["y_test"].astype(np.int64)
    snr = d["snr_test"]

    snn = build_snn(model, cal_x, out_percentile=args.pct,
                    hidden_percentile=args.pct, input_rate_scale=args.scale,
                    w_bits=args.w_bits)
    pred, counts = snn_forward(x, snn, args.T, return_counts=True)
    acc = float((pred == y).mean())
    margin = counts[:, 1].astype(np.int64) - counts[:, 0].astype(np.int64)
    print(f"accuracy={acc*100:.2f}%  T={args.T} pct={args.pct}")
    print(f"thresholds={snn['th1']} {snn['th2']} {snn['th3']}  "
          f"bias ranges={np.abs(snn['b1']).max()} {np.abs(snn['b2']).max()} {np.abs(snn['b3']).max()}")

    # --- choose hardware cases: a spread of class / SNR / margin, all correct ---
    chosen = []
    for cls in (0, 1):
        idx = np.where((y == cls) & (pred == cls))[0]
        # sort by detection margin (higher = more confident)
        idx = idx[np.argsort(-np.abs(margin[idx]))]
        # take 2 confident, 1 medium, 1 near-boundary
        picks = [idx[0], idx[len(idx) // 8], idx[len(idx) // 2],
                 idx[min(len(idx) - 1, int(len(idx) * 0.80))]]
        chosen.extend(picks)
    chosen = chosen[:args.cases]
    chosen = sorted(chosen, key=lambda i: (y[i], -abs(margin[i])))

    feats = x[chosen]
    cts = counts[chosen].astype(np.int64)
    ys = y[chosen]
    margins = margin[chosen]
    for k, i in enumerate(chosen):
        print(f"case {k}: idx={i} y={ys[k]} snr={snr[i]:5.1f}dB "
              f"counts={cts[k]} margin={margins[k]:+d} pred={pred[i]}")

    # --- weights ---
    n1 = pack_weight_file(snn["W1"], os.path.join(args.outdir, "w1.mem"), args.lanes, args.w_bits)
    n2 = pack_weight_file(snn["W2"], os.path.join(args.outdir, "w2.mem"), args.lanes, args.w_bits)
    n3 = pack_weight_file(snn["W3"], os.path.join(args.outdir, "w3.mem"), args.lanes, args.w_bits)
    pack_bias_file(snn["b1"], os.path.join(args.outdir, "b1.mem"))
    pack_bias_file(snn["b2"], os.path.join(args.outdir, "b2.mem"))
    pack_bias_file(snn["b3"], os.path.join(args.outdir, "b3.mem"))
    print(f"weights: w1={n1} words, w2={n2}, w3={n3}")

    # --- features + expected results ---
    with open(os.path.join(args.outdir, "hw_features.mem"), "w") as f:
        for feat in feats:
            val = int.from_bytes(feat.tobytes(), "little")
            f.write(f"{val:0512x}\n")
    with open(os.path.join(args.outdir, "hw_expected.mem"), "w") as f:
        for k in range(len(chosen)):
            dec = 1 if cts[k, 1] > cts[k, 0] else 0
            exp = (int(cts[k, 0]) << 32) | (int(cts[k, 1]) << 16) | dec
            f.write(f"{exp:016x}\n")

    # --- RTL config header ---
    with open("rtl/snn_params.vh", "w") as f:
        f.write("// auto-generated by python/export_hw.py\n")
        f.write(f"`define SNN_T {args.T}\n")
        f.write(f"`define SNN_TH1 {int(snn['th1'])}\n")
        f.write(f"`define SNN_TH2 {int(snn['th2'])}\n")
        f.write(f"`define SNN_TH3 {int(snn['th3'])}\n")
        f.write("`define SNN_LEAK 0\n")

    n_in = int(snn["W1"].shape[1]); h1 = int(snn["W1"].shape[0])
    h2 = int(snn["W2"].shape[0]); n_out = int(snn["W3"].shape[0])
    meta = dict(model=args.model, pct=args.pct, T=args.T, lanes=args.lanes, w_bits=args.w_bits,
                layers=[n_in, h1, h2, n_out],
                synapses=int(snn["W1"].size + snn["W2"].size + snn["W3"].size),
                params=int(snn["W1"].size + h1 + snn["W2"].size + h2 +
                           snn["W3"].size + n_out),
                accuracy=acc,
                thresholds=[int(snn["th1"]), int(snn["th2"]), int(snn["th3"])],
                lambdas=[float(snn["lam1"]), float(snn["lam2"]), float(snn["lam3"])],
                output_offset=float(snn["C"]),
                cases=[dict(idx=int(i), y=int(ys[k]), snr=float(snr[i]),
                            counts=[int(cts[k, 0]), int(cts[k, 1])],
                            decision=int(pred[i]), margin=int(margins[k]))
                       for k, i in enumerate(chosen)])
    with open(os.path.join(args.outdir, "meta.json"), "w") as f:
        json.dump(meta, f, indent=2)
    print(f"saved {args.outdir}/meta.json, rtl/snn_params.vh")


if __name__ == "__main__":
    main()
